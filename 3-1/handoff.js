/* 지구과학 Ⅲ-1 태양계 행성의 겉보기 운동 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "남쪽 하늘을 볼 때는 <b>왼쪽이 동쪽, 오른쪽이 서쪽</b>이다. 행성이 별자리 사이를 <b>서 → 동</b>으로 옮겨 가면 순행, <b>동 → 서</b>로 옮겨 가면 역행.",
  "역행은 행성이 거꾸로 도는 것이 아니다. 지구와 행성이 가장 가까워질 때(외행성은 <b>충</b>, 내행성은 <b>내합</b> 부근) 안쪽 행성이 바깥쪽 행성을 <b>추월</b>하며 생기는 겉보기 운동이다.",
  "<b>이각</b>은 지구에서 볼 때 태양과 행성이 벌어진 각이다. 행성이 태양의 동쪽에 있으면 <b>동방 이각</b>, 서쪽에 있으면 <b>서방 이각</b>."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "epA", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「이각과 관측 조건」에서 <b>이각</b> 하나로 행성이 언제, 어느 쪽 하늘에 보이는지 정하고, 금성의 위상으로 두 우주관을 다시 견줍니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "epB", need: "01", doneKey: "epA",
  lines: [D01[2], D01[0], "이 이야기에서는 이각이 <b>동방</b>이면 해 진 뒤 <b>서쪽 하늘</b>, <b>서방</b>이면 해 뜨기 전 <b>동쪽 하늘</b>에서 행성을 찾습니다."],
  check: { q: "어느 날 금성이 태양보다 동쪽으로 40° 떨어져 보였다. 이 금성은 무엇이고 언제 볼 수 있을까?", options: ["서방 이각 · 새벽 동쪽 하늘", "동방 이각 · 초저녁 서쪽 하늘", "충 · 한밤중 남쪽 하늘"], a: 1, why: "태양의 동쪽에 있으므로 동방 이각이고, 태양보다 늦게 지므로 해 진 뒤 서쪽 하늘에 보입니다." }
});

/* 03 — 시작 전 (앞 소단원과 무관하게 시작) */
window.sthBridge({
  ep: "epC", always: true, title: "시작 전 1분 · 이 이야기에 필요한 것은 두 가지뿐",
  lines: [
    "<b>삭</b>은 달이 태양과 같은 쪽에 있을 때(달이 안 보임), <b>망</b>은 달이 태양의 반대쪽에 있을 때(보름달)이다. 삭망월은 약 29.5일.",
    "<b>황도</b>는 1년 동안 태양이 천구에서 지나가는 길이다. 달이 지나가는 길(백도)은 황도와 조금 어긋나 있다."
  ],
  note: "01 · 02를 하지 않았어도 바로 시작할 수 있습니다."
});
})();
