/* 지구과학 Ⅱ-1 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "역전되지 않았다면 <b>아래 지층이 먼저</b> 쌓였다(지층 누중). 그래서 먼저 퇴적구조(사층리·점이층리·건열·연흔)로 <b>위아래</b>를 확인한다.",
  "다른 암석을 <b>자르고 들어간 암석이 나중</b>이다(관입). 부정합면 위아래 사이에는 쌓이지 않은 긴 시간이 빠져 있다.",
  "생물은 시대에 따라 바뀐다(<b>동물군 천이</b>, 식물도 같다). 그래서 <b>같은 화석이 나오는 지층은 같은 시대</b>로 볼 수 있다."
];
var D02 = [
  "모원소가 절반으로 줄어드는 시간이 <b>반감기</b>. 반감기가 n번 지나면 (1/2)<sup>n</sup>이 남고, <b>절대연령 = n × 반감기</b>.",
  "재려는 나이에 맞는 시계를 고른다. 수만 년까지는 <b>¹⁴C</b>, 수백만~수십억 년은 <b>⁴⁰K·²³⁸U</b>.",
  "멀리 떨어진 지역의 지층은 <b>건층(응회암 등)</b>과 <b>표준 화석</b>으로 이어 붙인다. 지층의 두께는 시간이 아니라 퇴적 속도가 정한다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "epA", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「절대연령과 지층 대비」에서 두 지역의 지층을 이어 붙일 때, 03 「지질 시대와 화석」에서 화석으로 시대를 가를 때 다시 쓰입니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "epB", need: "01", doneKey: "epA",
  lines: [D01[0], D01[2], "이 이야기에서는 그 순서에 <b>실제 나이(절대연령)</b>를 붙이고, 멀리 떨어진 두 지역의 지층을 건층과 표준 화석으로 이어 붙입니다."],
  check: { q: "역전되지 않은 지층에서 ㉮ 위에 ㉯, 그 위에 ㉰가 놓여 있다. 가장 먼저 쌓인 지층은?", options: ["㉮", "㉯", "㉰"], a: 0, why: "지층 누중의 법칙: 역전되지 않았다면 아래 지층이 먼저 쌓였습니다." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "epB", title: "이 이야기에서 챙겨 갈 세 줄", lines: D02,
  note: "03 「지질 시대와 화석」의 ‘몇 억 년 전’이라는 숫자는 모두 이렇게 잰 <b>절대연령</b>이고, 좋은 <b>표준 화석</b>의 조건도 여기서 이어집니다."
});

/* 03 ← 02 */
window.sthBridge({
  ep: "epC", need: "02", doneKey: "epB",
  lines: [D02[0], D02[2], "이 이야기에서는 지질 시대의 경계를 46억 년 달력 위에 놓고, 어떤 생물이 좋은 <b>표준 화석</b>이 되는지 따집니다."],
  check: { q: "반감기가 12.5억 년인 ⁴⁰K가 처음 양의 25 % 남아 있다. 이 암석의 절대연령은?", options: ["12.5억 년", "25억 년", "37.5억 년", "50억 년"], a: 1, why: "25 %는 (1/2)², 반감기가 2번 지났으므로 2 × 12.5억 = 25억 년입니다." }
});
})();
